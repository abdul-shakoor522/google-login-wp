/**
 * Retrieves the plugin settings from the WordPress options table.
 *
 * WHY a wrapper function instead of calling get_option() directly?
 * 1. We can add defaults in ONE place — if we add a new setting later,
 *    we only update this function, not every place that reads settings.
 * 2. If the option doesn't exist yet (plugin just installed), we still
 *    get a usable array instead of FALSE.
 * 3. Every file can call glwp_get_settings() without knowing the option name.
 *
 * @return array Plugin settings with defaults for any missing keys.
 */
function glwp_get_settings()
{
    // get_option( 'option_name', $default ) returns $default if option doesn't exist.
    $saved = get_option('glwp_settings', array());

    // These are our "factory defaults" — what the plugin uses if a value
    // hasn't been saved yet.
    $defaults = array(
        'client_id'     => '',
        'client_secret' => '',
        'auto_register' => '1',
    );

    // array_merge: $saved values OVERRIDE $defaults.
    // So if 'client_id' is saved, it wins over the empty string default.
    // If a new setting was added to $defaults that isn't in $saved yet,
    // the default value is used automatically.
    return array_merge($defaults, $saved);
}

/**
 * Returns the Google OAuth Client ID from settings.
 *
 * @return string Client ID or empty string if not configured.
 */
function glwp_get_client_id()
{
    $settings = glwp_get_settings();
    return $settings['client_id'];
}

/**
 * Returns the Google OAuth Client Secret from settings.
 *
 * @return string Client Secret or empty string if not configured.
 */
function glwp_get_client_secret()
{
    $settings = glwp_get_settings();
    return $settings['client_secret'];
}

/**
 * Checks whether automatic account registration is enabled.
 *
 * @return bool True if new users can be auto-created, false otherwise.
 */
function glwp_is_auto_register_enabled()
{
    $settings = glwp_get_settings();
    return '1' === $settings['auto_register'];
}

// =============================================================================
// STATE / NONCE HELPERS (Anti-CSRF)
// =============================================================================

/**
 * Generates a cryptographically secure random state string and stores it.
 *
 * The "state" parameter is OAuth's equivalent of a nonce — it proves that
 * the callback response was triggered by THIS user on THIS site, not injected
 * by an attacker.
 *
 * Flow:
 * 1. We generate a random string
 * 2. We store it in a WordPress transient (temporary database entry)
 * 3. We send it to Google as part of the auth URL
 * 4. Google sends it back in the callback
 * 5. We check it matches what we stored → if yes, safe to continue
 *
 * WHY transients instead of PHP sessions?
 * WordPress doesn't start sessions by default, and starting sessions
 * on login pages can cause issues with caching plugins and hosting providers.
 * Transients use the WordPress database (or object cache), which is more
 * reliable in WordPress environments.
 *
 * @return string The generated state string (32 hex characters).
 */
function glwp_generate_oauth_state()
{
    // wp_generate_password with only hex-safe characters.
    // bin2hex( random_bytes(16) ) = 32 character hex string.
    // random_bytes() uses the operating system's cryptographically
    // secure random number generator — much stronger than rand() or mt_rand().
    $state = bin2hex(random_bytes(16));

    // Store in a transient that expires in 10 minutes.
    // The key includes the state value itself so we can look it up.
    // 'glwp_state_' prefix namespaces it to our plugin.
    set_transient('glwp_state_' . $state, '1', 10 * MINUTE_IN_SECONDS);
    // MINUTE_IN_SECONDS is a WordPress constant = 60.
    // 10 * 60 = 600 seconds = 10 minutes.
    // After 10 minutes the transient auto-deletes — expired states cannot be used.

    return $state;
}

/**
 * Validates that a state string was generated by us (not fabricated by an attacker).
 *
 * @param string $state The state string received in the callback URL.
 * @return bool True if valid and unused, false if invalid or expired.
 */
function glwp_validate_oauth_state($state)
{
    // Sanitize first — the state came from a URL parameter (user input).
    $state = sanitize_text_field($state);

    // Basic length check — our states are always 32 hex characters.
    if (empty($state) || strlen($state) !== 32) {
        return false;
    }

    // Check if this state exists in our transients.
    $stored = get_transient('glwp_state_' . $state);

    if (false === $stored) {
        // Transient doesn't exist: either expired, never existed, or already used.
        return false;
    }

    // DELETE the transient immediately after validation.
    // WHY? This makes the state "single use" — it cannot be replayed.
    // If an attacker somehow got a valid state and tried to use it twice,
    // the second attempt would fail because we deleted it after the first use.
    delete_transient('glwp_state_' . $state);

    return true;
}

