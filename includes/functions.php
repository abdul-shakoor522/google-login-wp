/**
 * Logs a message to the WordPress debug log.
 *
 * Only logs when WP_DEBUG and WP_DEBUG_LOG are both enabled in wp-config.php.
 * In production, these should be FALSE so nothing is logged.
 *
 * Usage:
 *   glwp_log( 'Token exchange failed', $response_data );
 *   glwp_log( 'User created with ID: ' . $user_id );
 *
 * To see logs: check wp-content/debug.log
 *
 * @param string $message Description of what's happening.
 * @param mixed  $data    Optional extra data to dump (array, object, etc.).
 */
function glwp_log($message, $data = null)
{
    if (! defined('WP_DEBUG') || ! WP_DEBUG) {
        return; // Don't log in production.
    }
    if (! defined('WP_DEBUG_LOG') || ! WP_DEBUG_LOG) {
        return; // Don't log if logging is disabled.
    }

    $prefix = '[Google Login WP] ';
    if (null !== $data) {
        // phpcs:ignore WordPress.PHP.DevelopmentFunctions.error_log_error_log
        error_log($prefix . $message . ' | Data: ' . print_r($data, true));
    } else {
        // phpcs:ignore WordPress.PHP.DevelopmentFunctions.error_log_error_log
        error_log($prefix . $message);
    }
}
