/**
 * Redirects to the login page with an error message.
 *
 * We use this instead of wp_die() because:
 * - wp_die() shows a plain error page — bad UX for a login flow.
 * - Redirecting to login with an error message shows the user the login
 *   form again with a friendly message — much better UX.
 *
 * WordPress's login page automatically displays ?error=key messages
 * when we use the 'login_message' filter, but the simpler approach is
 * to add a custom query var and display it.
 *
 * @param string $error_code A short string identifying the error (e.g., 'state_mismatch').
 */
function glwp_redirect_with_error($error_code)
{
    // sanitize_key ensures the error code is safe to put in a URL.
    $error_code = sanitize_key($error_code);

    // Build the redirect URL: wp-login.php?glwp_error=error_code
    $url = add_query_arg(
        array('glwp_error' => $error_code),
        wp_login_url()
    );

    // wp_safe_redirect only allows redirecting to trusted domains.
    // This prevents "open redirect" attacks where an attacker tricks
    // your site into redirecting to a malicious external URL.
    wp_safe_redirect($url);
    exit; // ALWAYS call exit after wp_safe_redirect. Without it, PHP keeps running.
}

/**
 * Displays error messages on the login page from our OAuth flow.
 *
 * Hooked to 'login_messages' — this filter lets plugins add messages
 * above the login form.
 *
 * @param string $message Existing login messages (from WordPress itself).
 * @return string Updated messages HTML.
 */
function glwp_display_login_error($message)
{
    // phpcs:ignore WordPress.Security.NonceVerification.Recommended
    if (! isset($_GET['glwp_error'])) {
        return $message;
    }

    // sanitize_key: only allows lowercase letters, numbers, hyphens, underscores.
    $error_code = sanitize_key($_GET['glwp_error']);

    // Map error codes to human-readable messages.
    // WHY error codes instead of passing the message in the URL?
    // 1. Internationalization: we translate here, not in the URL.
    // 2. Security: user input in URLs could contain HTML/scripts. Error codes are safe.
    // 3. Cleaner URLs.
    $errors = array(
        'state_mismatch'    => __('Security check failed. Please try logging in again.', 'google-login-wp'),
        'no_code'           => __('Google did not return an authorization code. Please try again.', 'google-login-wp'),
        'token_failed'      => __('Could not connect to Google. Please try again later.', 'google-login-wp'),
        'userinfo_failed'   => __('Could not retrieve your Google profile. Please try again.', 'google-login-wp'),
        'no_email'          => __('Your Google account does not have a verified email address.', 'google-login-wp'),
        'registration_off'  => __('Account registration is disabled. Contact the site administrator.', 'google-login-wp'),
        'login_failed'      => __('Login failed. Please try again or contact the administrator.', 'google-login-wp'),
        'not_configured'    => __('Google Login is not configured. Please contact the site administrator.', 'google-login-wp'),
    );

    if (! array_key_exists($error_code, $errors)) {
        // Unknown error code — show a generic message.
        $error_text = __('An unknown error occurred. Please try again.', 'google-login-wp');
    } else {
        $error_text = $errors[$error_code];
    }

    // Build the message HTML.
    // WordPress login uses <div class="message error"> for error notices.
    // esc_html() prevents any HTML in the error text from rendering as HTML.
    $message .= '<div class="message error" id="glwp-login-error">';
    $message .= esc_html($error_text);
    $message .= '</div>';

    return $message;
}
add_filter('login_messages', 'glwp_display_login_error');

